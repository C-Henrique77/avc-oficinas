-- ==========================================================
-- ETAPA 1: TABELA DE PARTICIPANTES
-- ==========================================================

-- Armazena as pessoas que podem participar das oficinas.

CREATE TABLE participantes (

    -- Identificador único, gerado automaticamente.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Nome do participante. Não pode ser vazio.
    nome VARCHAR(120) NOT NULL
        CHECK (LENGTH(TRIM(nome)) > 0),

    -- E-mail único para identificar o participante.
    email VARCHAR(150) NOT NULL UNIQUE
);


-- ==========================================================
-- ETAPA 2: TABELA DE OFICINAS
-- ==========================================================

-- Armazena as oficinas oferecidas pela instituição.

CREATE TABLE oficinas (

    -- Identificador único da oficina.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Nome ou título da oficina.
    titulo VARCHAR(150) NOT NULL
        CHECK (LENGTH(TRIM(titulo)) > 0),

    -- Quantidade máxima de participantes.
    -- Deve ser maior que zero.
    capacidade INTEGER NOT NULL
        CHECK (capacidade > 0),

    -- Quantidade atual de vagas disponíveis.
    vagas_disponiveis INTEGER NOT NULL,

    -- Impede números negativos ou valores
    -- maiores que a capacidade da oficina.
    CONSTRAINT vagas_validas CHECK (
        vagas_disponiveis >= 0
        AND vagas_disponiveis <= capacidade
    )
);


-- ==========================================================
-- ETAPA 3: TABELA DE INSCRIÇÕES
-- ==========================================================

-- Registra as inscrições dos participantes nas oficinas.

CREATE TABLE inscricoes (

    -- Identificador único da inscrição.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Identifica o participante inscrito.
    participante_id BIGINT NOT NULL
        REFERENCES participantes(id)
        ON DELETE RESTRICT,

    -- Identifica a oficina escolhida.
    oficina_id BIGINT NOT NULL
        REFERENCES oficinas(id)
        ON DELETE RESTRICT,

    -- Data e horário em que a inscrição foi registrada.
    data_registro TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    -- Situação atual da inscrição.
    -- ATIVA     = participante está inscrito.
    -- CANCELADA = inscrição foi cancelada.
    situacao VARCHAR(15) NOT NULL DEFAULT 'ATIVA'
        CHECK (situacao IN ('ATIVA', 'CANCELADA'))
);


-- ==========================================================
-- ETAPA 4: REGRAS ADICIONAIS E ÍNDICES
-- ==========================================================

-- Impede que o mesmo participante tenha
-- duas inscrições ATIVAS na mesma oficina.
-- Inscrições canceladas não impedem nova inscrição.

CREATE UNIQUE INDEX uq_inscricao_ativa
ON inscricoes(participante_id, oficina_id)
WHERE situacao = 'ATIVA';


-- Facilita consultas de inscrições por oficina.

CREATE INDEX idx_inscricoes_oficina
ON inscricoes(oficina_id);


